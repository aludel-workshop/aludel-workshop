// Phase A: the pre-J4 code (root given as argv[2]) writes items, an agent run and a person run with positional verdicts and evidence.
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const [root, dir] = process.argv.slice(2);
const m = async name => import(join(root, 'apps/portal/server', name));
const { createUser, initAccounts } = await m('accounts.mjs');
const { agentRuns, initAgentRuns } = await m('agent-runs.mjs');
const { initKnowledge, knowledge } = await m('knowledge.mjs');
const { initOnboarding, loadCatalogs, onboarding } = await m('onboarding.mjs');
const { ensureProductWorkspace } = await m('product-workspace.mjs');
const { openSecretStore } = await m('secret-store.mjs');
const { openDatabase } = await m('storage.mjs');
const { initSymphonyWorker, symphonyWorker } = await m('symphony-worker.mjs');
const { initWorkRuns, workRuns } = await m('work-runs.mjs');
const { initWorkflow } = await m('workflow.mjs');
const git = (cwd, ...args) => execFileSync('git', args, { cwd, stdio: 'pipe' }).toString().trim();
mkdirSync(dir, { recursive: true });
const db = openDatabase(join(dir, 'machine.sqlite'));
initWorkflow(db); ensureProductWorkspace(db); initAccounts(db); initOnboarding(db); initKnowledge(db); initAgentRuns(db); initSymphonyWorker(db); initWorkRuns(db);
const catalogs = loadCatalogs(join(root, 'apps/portal/config'));
const know = knowledge({ db, catalogs, packs: catalogs.packs });
const flows = onboarding({ db, catalogs, secrets: openSecretStore(dir), workspaceRoot: join(dir, 'workspaces'), assetRoot: join(dir, 'assets'), createWorkspace: () => {}, know });
const owner = createUser(db, { email: 'owner@example.invalid', name: 'Owner', password: 'correct-horse-battery' });
const { token } = flows.saveDraft(null, { profile: 'planner' });
flows.saveDraft(token, { name: 'Rehearsal', pitch: 'A disposable product.' });
const projectId = flows.claimDraft(token, owner, owner).project.id;
know.ensureAgents(projectId); know.ensurePackData(projectId); know.ensureRoutines(projectId); know.migrateWork(projectId);
know.ensureBrief(projectId); know.ensureLibrary(projectId); know.ensurePlan(projectId); know.ensureDesign(projectId);
const workspace = db.prepare('SELECT workspace_path FROM project_setup WHERE project_id = ?').get(projectId).workspace_path;
mkdirSync(workspace, { recursive: true }); git(workspace, 'init', '-q'); writeFileSync(join(workspace, 'README.md'), 'Pinned base\n'); git(workspace, 'add', '.');
git(workspace, '-c', 'user.name=Test', '-c', 'user.email=test@example.invalid', 'commit', '-qm', 'initial');
const profile = know.defaultProfile(projectId);
know.update(projectId, profile.id, { model: '', effort: 'medium' }, { rationale: 'fixture' });
const workerRoot = join(dir, 'worker'); mkdirSync(workerRoot);
const worker = symphonyWorker({ db, know, workspaceRoot: workerRoot });
const scope = worker.authenticate('Bearer ' + worker.issueToken(owner, projectId, profile.id).token);
const runs = agentRuns({ db, know, secrets: openSecretStore(dir), providers: catalogs.agentProviders.providers, worker, symphonyDispatch: true, callModel: async () => { throw new Error('no'); } });
const history = workRuns({ db, know });
// An agent run, submitted, with evidence by criterion position and a positional verdict.
const agent = know.createWork(projectId, { action: 'product.brief', title: 'Agent brief', assignee: { kind: 'agent', id: profile.id }, checks: ['It is one sentence', 'It names the user'] }, owner.name);
if (agent.state === 'suggested') know.updateWork(owner, projectId, agent.id, { state: 'ready' });
runs.stage(owner, projectId, agent.id);
runs.start(owner, projectId, runs.view(projectId).find(value => value.state === 'draft').id);
const issue = worker.issues(scope, { states: ['Ready'] }).issues.find(value => value.native_ref.work_id === agent.id);
const clone = join(workerRoot, issue.identifier); git(dir, 'clone', workspace, clone); git(clone, 'checkout', '--detach', issue.native_ref.repository_commit);
writeFileSync(join(clone, '.git', 'aludel-base'), issue.native_ref.repository_commit + '\n');
worker.registerWorkspace(scope, { attemptId: issue.native_ref.attempt_id, path: clone }); worker.reserveRun(scope, { attemptId: issue.native_ref.attempt_id });
history.recordEvidence(issue.native_ref.attempt_id, history.checkEvidence(projectId, issue.native_ref.attempt_id, [{ criterion: 1, type: 'change', ref: 'Vision › Brief › Value', note: 'Names the user' }]));
worker.submitProposal(scope, { attemptId: issue.native_ref.attempt_id, proposal: { summary: 'A value claim.', content: { section: 'value', text: 'A pet for people who work alone.', note: 'From the request.', basis: 'The request.' }, usedInputs: [] } });
history.saveReview(projectId, agent.id, issue.native_ref.attempt_id, { verdict: { index: 1, value: 'reject', note: 'Which user?' } });
history.saveReview(projectId, agent.id, issue.native_ref.attempt_id, { verdict: { index: 0, value: 'accept' } });
// A person run with evidence by position, in review with a positional verdict; and an untouched ready item.
const person = know.createWork(projectId, { action: 'platform.docs', title: 'Person guide', assignee: { kind: 'person', id: owner.id }, checks: ['It names the owner', 'It has a date'] }, owner.name);
runs.stage(owner, projectId, person.id);
const started = history.startPerson(owner, projectId, person.id);
history.submitPerson(owner, projectId, person.id, started.id, { summary: 'Wrote the guide.', evidence: [{ criterion: 1, note: 'The date is in the header.' }] });
history.saveReview(projectId, person.id, started.id, { verdict: { index: 1, value: 'accept' } });
const ready = know.createWork(projectId, { action: 'platform.docs', title: 'Ready item', checks: ['First', 'Second', 'Third'] }, owner.name);
db.close();
console.log(JSON.stringify({ projectId, agent: agent.id, agentAttempt: issue.native_ref.attempt_id, person: person.id, personRun: started.id, ready: ready.id, ownerId: owner.id }));
