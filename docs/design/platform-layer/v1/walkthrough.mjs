// The v1 walkthrough: 25 screenshots at 1600x1000, then a 390 px horizontal-scroll check. Set PLAYWRIGHT_MODULE.
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE);
const base = new URL('./index.html', import.meta.url).href;
const out = new URL('./shots/', import.meta.url).pathname;
import { mkdirSync } from 'node:fs'; mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('console', m => m.type() === 'error' && errors.push(m.text()));
let n = 0; const shot = async (name) => { n++; await page.waitForTimeout(250); await page.evaluate(() => document.querySelectorAll('.toast').forEach(t => t.remove())); await page.screenshot({ path: `${out}${String(n).padStart(2, '0')}-${name}.png` }); console.log('shot', n, name); };
const step = async (label, fn) => { try { await fn(); } catch (e) { errors.push(`${label}: ${e.message.split('\n')[0]}`); } };
await page.goto(base + '#code/overview'); await page.waitForTimeout(1500);
await shot('code-overview');
await step('c4 click', () => page.click('.c4 .box[data-sel="api"]'));
await shot('explorer-api-part');
await step('open borrowing', () => page.click('.tn[data-node="c-borrow"]'));
await shot('explorer-borrowing');
await step('open approve', () => page.click('.tn[data-unit="approveRequest"]'));
await shot('explorer-approve-source');
await step('gutter mark', () => page.click('[data-unit-mark="returnTool"]'));
await shot('explorer-return-untested');
await step('filter suspect', () => page.click('[data-f="suspect"]'));
await shot('explorer-filter-suspect');
await step('files view', () => page.click('[data-view="files"]'));
await shot('explorer-files-suspect');
await step('all', () => page.click('[data-f="all"]'));
await step('search', async () => { await page.fill('#tq', ''); await page.type('#tq', 'docker'); });
await shot('explorer-search-docker');
await step('dockerfile', () => page.click('.tn[data-file="Dockerfile"]'));
await shot('explorer-dockerfile');
await step('clear', async () => { await page.fill('#tq', ''); await page.click('[data-view="structure"]'); });
await step('blocks', () => page.click('.tn[data-node="c-blocks"]')); await step('change', () => page.click('.tn[data-unit="legacyTile"]'));
await step('req', () => page.click('[data-act="change"]'));
await shot('request-change');
await step('send', () => page.click('[data-act="send-change"]'));
await page.goto(base + '#code/dependencies'); await shot('code-dependencies');
await page.goto(base + '#code/changes'); await shot('code-changes');
await page.goto(base + '#code/releases'); await shot('code-releases');
await page.goto(base + '#deploy/pipeline'); await shot('deploy-pipeline');
await page.goto(base + '#deploy/env/production/variables'); await page.waitForTimeout(300);
await step('edit var', async () => { const i = page.locator('[data-var="MAIL_FROM:production"]'); await i.click(); await i.press('End'); await i.type('.uk'); });
await shot('deploy-variables-edited');
await page.goto(base + '#deploy/env/production/overview'); await shot('deploy-env-overview');
await page.goto(base + '#deploy/pipeline');
await step('promote', () => page.click('[data-act="promote"]')); await shot('deploy-promote');
await step('do promote', () => page.click('[data-act="do-promote"]'));
await page.goto(base + '#deploy/env/production/history'); await shot('deploy-history-after');
await page.goto(base + '#deploy/env/production/logs'); await shot('deploy-logs');
await page.goto(base + '#deploy/env/production/settings'); await shot('deploy-settings');
await page.goto(base + '#deploy/database'); await shot('deploy-database');
await page.goto(base + '#deploy/monitoring'); await shot('deploy-monitoring');
await page.goto(base + '#code/explorer');
await step('notes', () => page.click('[data-act="notes"]')); await shot('review-notes');
// Phone width
await page.setViewportSize({ width: 390, height: 844 });
for (const h of ['#code/overview', '#code/explorer', '#deploy/pipeline', '#deploy/env/production/variables', '#code/releases']) {
  await page.goto(base + h); await page.waitForTimeout(300);
  const over = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth);
  if (over > 0) errors.push(`horizontal scroll ${over}px at 390 on ${h}: ` + await page.evaluate(() => [...document.querySelectorAll('main *')].filter(el => el.getBoundingClientRect().right > innerWidth + 1 && !el.closest('.tw,.src,.logs,.tabs,.tree-body')).slice(0, 4).map(el => el.tagName + '.' + el.className).join(' | ')));
}
await page.goto(base + '#code/explorer'); await step('phone unit', () => page.click('.tn[data-unit="approveRequest"]')); await shot('phone-explorer');
await page.goto(base + '#deploy/pipeline'); await shot('phone-pipeline');
await browser.close();
console.log(errors.length ? 'ERRORS\n' + errors.join('\n') : 'NO ERRORS');
